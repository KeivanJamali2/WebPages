def get_translation(key, lang='en'):
    """Get translation for a key in specified language."""
    if lang not in translations:
        lang = 'en'
    return translations[lang].get(key, translations['en'].get(key, key))


def get_all_translations(lang='en'):
    """Get all translations for a language."""
    if lang not in translations:
        lang = 'en'
    return translations[lang]


class Translator:
    """Translator class for template usage."""
    
    def __init__(self, lang='en'):
        self.lang = lang if lang in translations else 'en'
    
    def __call__(self, key):
        return get_translation(key, self.lang)
    
    def set_language(self, lang):
        self.lang = lang if lang in translations else 'en'
    
    def get_direction(self):
        """Return text direction for the current language."""
        return 'rtl' if self.lang == 'fa' else 'ltr'
    
    def get_all(self):
        """Get all translations as dict."""
        return get_all_translations(self.lang)
